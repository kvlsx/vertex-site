const LOCALE = { en: 'en-GB', de: 'de-DE', ru: 'ru-RU', uk: 'uk-UA' };

let latest = null;

function applyLang(lang) {
    const dict = I18N[lang] || I18N.en;
    document.documentElement.lang = lang;
    const titleKey = document.documentElement.dataset.title;
    document.title = (titleKey && dict[titleKey]) || TITLES[lang] || TITLES.en;
    const desc = document.querySelector('meta[name="description"]');
    if (desc && !titleKey) { desc.setAttribute('content', DESCS[lang] || DESCS.en); }
    document.querySelectorAll('[data-t]').forEach((el) => {
        const v = dict[el.dataset.t];
        if (v === undefined) { return; }
        // Einige Texte enthalten bewusst <strong>, deshalb innerHTML.
        if (v.includes('<')) { el.innerHTML = v; } else { el.textContent = v; }
    });
    document.querySelectorAll('[data-t-label]').forEach((el) => {
        const v = dict[el.dataset.tLabel];
        if (v) { el.setAttribute('aria-label', v); }
    });
    document.querySelectorAll('[data-t-hide-empty]').forEach((el) => {
        el.hidden = !dict[el.dataset.t];
    });
    document.querySelectorAll('[data-lang]').forEach((b) => {
        b.setAttribute('aria-pressed', String(b.dataset.lang === lang));
    });
    try { localStorage.setItem('vertex-lang', lang); } catch (e) { /* egal */ }
    renderMeta(lang);
    document.dispatchEvent(new CustomEvent('vx:lang', { detail: lang }));
}

function renderMeta(lang) {
    const el = document.getElementById('meta');
    const dict = I18N[lang] || I18N.en;
    if (!latest || !el) { return; }
    const date = new Date(latest.published_at).toLocaleDateString(LOCALE[lang] || 'en-GB', {
        day: 'numeric', month: 'long', year: 'numeric'
    });
    el.textContent = `${latest.tag_name} · ${date} · ${dict['meta.fallback']}`;
}

document.querySelectorAll('[data-lang]').forEach((b) => {
    b.addEventListener('click', () => applyLang(b.dataset.lang));
});

